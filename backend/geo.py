_SUFFIX = ("站", "北", "南", "东", "西")


def coords_for(name):
    """站名/城市名 -> (lat, lon)，找不到返回 None."""
    if not name:
        return None
    name = str(name).strip()
    if name in CITY:
        return CITY[name]
    if name in ALIAS and ALIAS[name] in CITY:
        return CITY[ALIAS[name]]
    base = name
    for _ in range(2):  # 最多剥两层后缀：如"临沂北站"
        for s in _SUFFIX:
            if base.endswith(s) and len(base) > len(s) + 1:
                base = base[:-len(s)]
                break
        else:
            break
        if base in CITY:
            return CITY[base]
        if base in ALIAS and ALIAS[base] in CITY:
            return CITY[ALIAS[base]]
    return None


def corridor_score(p, a, b):
    """候选点 p 相对走廊 A->B 的偏离分（越小越顺路，约等于公里）.

    垂直偏离 + 往回拐惩罚×2 + 冲过头惩罚×1.5。
    """
    (plat, plon), (alat, alon), (blat, blon) = p, a, b
    abx, aby = blon - alon, blat - alat
    apx, apy = plon - alon, plat - alat
    denom = abx * abx + aby * aby
    if denom == 0:
        return math.hypot(apx, apy) * 111
    t = (apx * abx + apy * aby) / denom
    cx, cy = abx * t, aby * t
    perp = math.hypot(apx - cx, apy - cy)
    L = math.sqrt(denom)
    if t < 0:
        extra = -t * L * 2.0
    elif t > 1:
        extra = (t - 1) * L * 1.5
    else:
        extra = 0.0
    return (perp + extra) * 111


def rank_hubs(from_name, to_name, hubs, prefer=None):
    """按走廊偏离给候选站排序；任一端无坐标则原样返回（静态兜底）.

    prefer：大枢纽集合，给加成（车密可靠，顺位相近时优先）。
    加成按 OD 长度自适应：min(150, 线路km×0.06)——长距离线路上，
    直线地理会系统性低估 trunk 枢纽（京广相对直线是个大弯，郑州/北京
    看着偏，实际车最多），线路越长越要信枢纽。短线则几乎不加。
    """
    a = coords_for(from_name)
    b = coords_for(to_name)
    if a is None or b is None:
        return list(hubs)
    seg_km = math.hypot(b[1] - a[1], b[0] - a[0]) * 111
    bonus = min(150.0, seg_km * 0.06)
    prefer = set(prefer or ())
    scored = []
    for h in hubs:
        c = coords_for(h)
        if c is None:
            s = float("inf")
        else:
            s = corridor_score(c, a, b) - (bonus if h in prefer else 0)
        scored.append((s, h))
    scored.sort(key=lambda x: x[0])
    return [h for _, h in scored]
